def page(n, per_page=6):
    qs = Q[n]
    out = []
    for i in range(0, len(qs), per_page):
        title = 'Interview questions' if i == 0 else 'Interview questions (continued)'
        out.append([('h2', '', title), ('raw', '<div style="font-size:0.93em">')] + [('ask', q, a, t) for q, a, t in qs[i:i + per_page]] + [('raw', '</div>')])
    return out

def add(notes, n, per_page=6):
    """insert the interview page(s) before the last page and renumber the h2 badges"""
    pages = notes[:-1] + page(n, per_page) + notes[-1:]
    out, k = [], 0
    for pg in pages:
        o = []
        for b in pg:
            if b[0] == 'h2':
                k += 1; b = ('h2', str(k)) + tuple(b[2:])
            o.append(b)
        out.append(o)
    return out
